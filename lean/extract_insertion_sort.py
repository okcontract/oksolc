import argparse
import hashlib
from pathlib import Path

from extract_compiler import Unsupported
from extract_storage import function, lex

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "src/libevmasm/expression_classes.zig"
OUTPUT = ROOT / "lean/Compiler/Extraction/InsertionSortProgram.lean"


def binding(data, text):
    tokens, wanted = lex(data.decode()), lex(text)
    if sum(tokens[i:i + len(wanted)] == wanted for i in range(len(tokens))) != 1:
        raise Unsupported("missing or ambiguous sort binding: " + text)


def extract(sort_source, compiler_source):
    binding(compiler_source, 'const std = @import("std");')
    binding(compiler_source, "pub const Id = u32;")
    # Reuse the established normalization boundary, but require this actual
    # production call and copied destination, not an unrelated test invocation.
    p = function(compiler_source, "fn init(allocator: std.mem.Allocator, item: *const AssemblyItem, arguments: []const Id, buffer: []Id) !NormalizedArguments")
    p.expect("{ if (!SemanticInformation.isCommutativeOperation(item) or arguments.len < 2)"
             " return .{ .items = arguments }; const normalized = if (arguments.len <= buffer.len)"
             " buffer[0..arguments.len] else try allocator.alloc(Id, arguments.len);"
             " @memcpy(normalized, arguments); std.sort.insertion(Id, normalized, {}, std.sort.asc(Id));"
             " return .{ .items = normalized, .owned = if (arguments.len > buffer.len) normalized else null, }; }")
    for alias in ('const std = @import("std.zig");', 'const assert = std.debug.assert;', 'const mem = std.mem;'):
        binding(sort_source, alias)
    p = function(sort_source, "pub fn insertion(comptime T: type, items: []T, context: anytype, comptime lessThanFn: fn (@TypeOf(context), lhs: T, rhs: T) bool,) void")
    p.expect("{ const Context = struct { items: []T, sub_ctx: @TypeOf(context),"
             " pub fn lessThan(ctx: @This(), a: usize, b: usize) bool {"
             " return lessThanFn(ctx.sub_ctx, ctx.items[a], ctx.items[b]); }"
             " pub fn swap(ctx: @This(), a: usize, b: usize) void {"
             " return mem.swap(T, &ctx.items[a], &ctx.items[b]); } };"
             " insertionContext(0, items.len, Context{ .items = items, .sub_ctx = context }); }")
    p = function(sort_source, "pub fn insertionContext(a: usize, b: usize, context: anytype) void")
    p.expect("{ assert(a <= b); var i = a + 1; while (i < b) : (i += 1) {"
             " var j = i; while (j > a and context.lessThan(j, j - 1)) : (j -= 1) {"
             " context.swap(j, j - 1); } } }")
    p = function(sort_source, "pub fn asc(comptime T: type) fn (void, T, T) bool")
    p.expect("{ return struct { pub fn inner(_: void, a: T, b: T) bool { return a")
    comparison = p.pop()
    if comparison not in ("<", "<=", ">", ">="):
        raise Unsupported("unsupported sort comparator")
    p.expect("b; } }.inner; }")
    return render(comparison, sort_source, compiler_source)


def render(comparison, sort_source, compiler_source):
    header = "/-\n// Copyright (C) 2026 OKcontract Pte. Ltd.\n// SPDX-License-Identifier: GPL-3.0\n-/\n"
    header += "-- Generated by extract_insertion_sort.py; do not edit.\n"
    for label, source in (("Zig std.sort", sort_source), ("Production caller", compiler_source)):
        header += "-- " + label + " SHA-256: " + hashlib.sha256(source).hexdigest() + "\n"
    return header + '''import Compiler.Extraction.InsertionSortModel

namespace Compiler.Extraction.InsertionSort
open Compiler.Algebraic

def less (a b : NodeId) : Bool := decide (a.toNat ''' + comparison + ''' b.toNat)

/-- The single extracted inner loop, instantiated by both list and heap
storage. The source short-circuit guard precedes all reads and exchanges. -/
def insertUsing (ops : Operations σ ε) : Nat → σ → Except ε Unit × σ
  | 0, state => (.ok (), state)
  | j + 1, state =>
    match ops.read state (j + 1) with
    | .error fault => (.error fault, state)
    | .ok current => match ops.read state j with
      | .error fault => (.error fault, state)
      | .ok previous =>
        if less current previous then
          match ops.exchange state (j + 1) j with
          | (.error fault, after) => (.error fault, after)
          | (.ok (), after) => insertUsing ops j after
        else (.ok (), state)

/-- The single extracted outer loop. Fuel exhaustion retains the current state
and has its own explicit outcome; the initial slice length remains fixed. -/
def passesUsing (ops : Operations σ ε) : Nat → Nat → Nat → σ → Except ε Unit × σ
  | 0, _, _, state => (.error ops.exhausted, state)
  | fuel + 1, stop, i, state =>
    if i < stop then
      match insertUsing ops i state with
      | (.error fault, after) => (.error fault, after)
      | (.ok (), after) => passesUsing ops fuel stop (i + 1) after
    else (.ok (), state)

def runUsing (ops : Operations σ ε) (length : Nat) (state : σ) : Except ε Unit × σ :=
  passesUsing ops (length + 1) length 1 state

/-- The production normalization sequence after destination selection. The copy
and sort boundaries retain their exact states and explicit model faults. -/
def copySortUsing (copy sort : σ → Except ε Unit × σ) (state : σ) : Except ε Unit × σ :=
  match copy state with
  | (.error fault, after) => (.error fault, after)
  | (.ok (), after) => sort after

def insert (j : Nat) (items : List NodeId) : Result :=
  Result.fromOutcome (insertUsing listOperations j items)

def passes (fuel stop i : Nat) (items : List NodeId) : Result :=
  Result.fromOutcome (passesUsing listOperations fuel stop i items)

def run (items : List NodeId) : Result :=
  Result.fromOutcome (runUsing listOperations items.length items)

/-- Native usize representability is separate from the natural-index model.
The caller's u32 element type is represented exactly by NodeId. -/
def checked (items : List NodeId) : Result :=
  if items.length < 2^64 then run items else .fault .indexWidth items

end Compiler.Extraction.InsertionSort
'''


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--zig-tree", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=OUTPUT)
    args = parser.parse_args()
    args.output.write_text(extract((args.zig_tree / "lib/std/sort.zig").read_bytes(), SOURCE.read_bytes()))
