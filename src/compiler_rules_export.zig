//! Deterministic proof input exported directly from the production algebraic
//! table and opcode definitions. Reviewed and proved in Lean, never trusted alone.
const std = @import("std");
const Algebraic = @import("libevmasm/algebraic_rules.zig");
const Instruction = @import("libevmasm/instruction.zig").Instruction;

comptime {
    if (@typeInfo(Instruction).@"enum".tag_type != u8)
        @compileError("compiler verification models instruction values as bytes");
}

pub fn main(init: std.process.Init) !void {
    var buffer: [4096]u8 = undefined;
    var output = std.Io.File.stdout().writerStreaming(init.io, &buffer);
    const writer = &output.interface;
    try writer.writeAll(
        \\/-
        \\// SPDX-License-Identifier: GPL-3.0
        \\// Copyright (C) 2026 OKcontract Pte. Ltd.
        \\-/
        \\
    );
    try writer.writeAll("import Compiler.Algebraic.Model\n\nnamespace Compiler.Algebraic\n\n");
    try writer.writeAll("-- Generated by compiler-rules-export; kernel-proved sound in Compiler.Algebraic.Proofs.\n");
    try writer.writeAll("def productionRules : List Rule := [\n");
    for (Algebraic.rules, 0..) |rule, index| {
        var name: [16]u8 = undefined;
        const opcode = std.ascii.lowerString(&name, @tagName(rule.instruction));
        try writer.print("  ⟨.{s}, .{s}, .{s}⟩{s}\n", .{
            opcode,
            @tagName(rule.guard),
            @tagName(rule.replacement),
            if (index + 1 == Algebraic.rules.len) "]" else ",",
        });
    }
    try writer.writeAll("\ndef productionBinaryOpcode : Contract.Yul.Binary → BitVec 8\n");
    for ([_]Instruction{
        .ADD,
        .SUB,
        .MUL,
        .DIV,
        .SDIV,
        .MOD,
        .SMOD,
        .EXP,
        .SIGNEXTEND,
        .AND,
        .OR,
        .XOR,
        .BYTE,
        .SHL,
        .SHR,
        .SAR,
        .LT,
        .GT,
        .SLT,
        .SGT,
        .EQ,
    }) |instruction| {
        var name: [16]u8 = undefined;
        const opcode = std.ascii.lowerString(&name, @tagName(instruction));
        try writer.print("  | .{s} => {d}\n", .{ opcode, @backingInt(instruction) });
    }
    try writer.writeAll("\ndef productionTernaryOpcode : Contract.Yul.Ternary → BitVec 8\n");
    for ([_]Instruction{ .ADDMOD, .MULMOD }) |instruction| {
        var name: [16]u8 = undefined;
        const opcode = std.ascii.lowerString(&name, @tagName(instruction));
        try writer.print("  | .{s} => {d}\n", .{ opcode, @backingInt(instruction) });
    }
    try writer.writeAll("\ndef productionNullaryOpcode : Contract.Yul.Nullary → BitVec 8\n");
    for ([_]Instruction{ .ADDRESS, .CALLER, .ORIGIN, .COINBASE }) |instruction| {
        var name: [16]u8 = undefined;
        const opcode = std.ascii.lowerString(&name, @tagName(instruction));
        try writer.print("  | .{s} => {d}\n", .{ opcode, @backingInt(instruction) });
    }
    try writer.writeAll("\nend Compiler.Algebraic\n");
    try writer.flush();
}
